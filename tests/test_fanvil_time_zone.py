def test_profile_clock_is_checked_and_caller_clock_is_replaced_before_string_validation():
    profile, _ = load_bundle("fanvil/x3u-pro")
    context = fixture_context()
    context["physical"]["time_zone"] = "Europe/Rome"
    context["clock"] = {"name": "ignored\ncaller clock"}
    assert validate_context(profile, context)["clock"] == ROME
    profile["capabilities"]["time_zones"]["Europe/Rome"]["name"] = "invalid\nprofile clock"
    with pytest.raises(ValueError, match="control character"):
        validate_context(profile, context)


def test_old_renderer_without_derived_clock_keeps_legacy_output():
    profile, templates = load_bundle("fanvil/x3u-pro")
    context = normalized_context(fixture_context())
    context["physical"]["time_zone"] = "Europe/Rome"
    context.pop("clock", None)
    env = SandboxedEnvironment(
        loader=DictLoader(templates),
        undefined=StrictUndefined,
        autoescape=True,
        keep_trailing_newline=True,
    )
    body = env.get_template(profile["outputs"][0]["template"]).render(deepcopy(context))
    assert sha256(body.encode()).hexdigest() == LEGACY_SHA256
