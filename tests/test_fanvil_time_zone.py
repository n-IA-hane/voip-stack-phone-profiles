"""Bounded clock goldens, separate from unqualified physical application.

Cisco/Fanvil ISPEC Appendix B maps Rome UTC+1 to offset4. The X3U Pro
manual Table29 describes automatic DST by locality. Native X3U Pro 2.12.20
read-only options on 2026-11-13 identify Rome locality13 and automatic mode1.
No native scripts or firmware are redistributed here.
"""

import xml.etree.ElementTree as ET
from copy import deepcopy
from datetime import datetime, timedelta
from hashlib import sha256
from zoneinfo import ZoneInfo

import pytest
from jinja2 import DictLoader, StrictUndefined
from jinja2.sandbox import SandboxedEnvironment
from test_catalog import catalog, load_bundle, only_output

from phone_profiles.build import fixture_context
from phone_profiles.render import normalized_context, validate_context

ROME = {"code": 4, "name": "UTC+1", "dst_type": 1, "dst_location": 13}
UTC = {"code": 0, "name": "UTC", "dst_type": 0, "dst_location": 0}
MAPPINGS = {"Europe/Rome": ROME, "UTC": UTC, "Etc/UTC": UTC}
LEGACY_SHA256 = "1f22c6af252eb75df9073e1a5099e68f5f9500eaeb09890e640218a1c55b8523"


def without_feature_sync(body):
    # DND sync is a separately documented additive change to the new profile.
    # All original fields still match the pre-clock/pre-FKS baseline exactly.
    return body.replace("<FeatureSync>1</FeatureSync>", "")


def test_legacy_context_defaults_to_no_clock_without_changing_bytes():
    profile, templates = load_bundle("fanvil/x3u-pro")
    original = fixture_context()
    normalized = normalized_context(original)
    assert normalized["physical"]["time_zone"] == ""
    assert "time_zone" not in original["physical"]
    assert (
        sha256(without_feature_sync(only_output(profile, templates, original)).encode()).hexdigest()
        == LEGACY_SHA256
    )
    original["clock"] = ROME
    assert validate_context(profile, original)["clock"] == {}
    assert (
        sha256(without_feature_sync(only_output(profile, templates, original)).encode()).hexdigest()
        == LEGACY_SHA256
    )


def test_only_x3u_pro_advertises_the_three_verified_time_zones():
    for entry in catalog()["profiles"]:
        if entry["id"] == "fanvil/x3u-pro":
            assert entry["capabilities"]["time_zones"] == MAPPINGS
        else:
            assert not entry["capabilities"].get("time_zones")


@pytest.mark.parametrize("zone,expected", MAPPINGS.items())
def test_clock_is_derived_from_capabilities_and_emits_only_four_fields(zone, expected):
    profile, templates = load_bundle("fanvil/x3u-pro")
    context = fixture_context()
    context["physical"]["time_zone"] = zone
    context["clock"] = {"code": 32, "name": "untrusted", "dst_type": 2, "dst_location": 99}
    validated = validate_context(profile, context)
    assert validated["clock"] == expected
    validated["clock"]["code"] = 99
    assert profile["capabilities"]["time_zones"][zone] == expected
    assert context["clock"]["code"] == 32
    root = ET.fromstring(only_output(profile, templates, context))
    (date,) = root.findall("./phone/date")
    assert {node.tag: node.text for node in date} == {
        "TimeZone": str(expected["code"]),
        "TimeZoneName": expected["name"],
        "DSTType": str(expected["dst_type"]),
        "DSTLocation": str(expected["dst_location"]),
    }
    assert root.find("timePlan") is None
    assert root.findtext("./dsskey/dssSide/Fkey/Value") == "430@1/bc"
    # Removing the four clock fields preserves every previously generated byte.
    body = only_output(profile, templates, context)
    start, end = body.index("<phone>"), body.index("</phone>") + len("</phone>")
    assert (
        sha256(without_feature_sync(body[:start] + body[end:]).encode()).hexdigest()
        == LEGACY_SHA256
    )


@pytest.mark.parametrize("month,expected_dst", [(1, 0), (7, 1)])
def test_rome_base_offset_stays_standard_in_winter_and_summer(month, expected_dst):
    profile, _ = load_bundle("fanvil/x3u-pro")
    context = fixture_context()
    context["physical"]["time_zone"] = "Europe/Rome"
    clock = validate_context(profile, context)["clock"]
    local = datetime(2026, month, 15, 12, tzinfo=ZoneInfo("Europe/Rome"))
    assert local.dst() == timedelta(hours=expected_dst)
    assert timedelta(minutes=15 * clock["code"]) == local.utcoffset() - local.dst()
    assert clock == ROME  # Automatic DST is not added to the base offset twice.


@pytest.mark.parametrize("identity", ["fanvil/x3u-pro", "fanvil/x4u", "yealink/t46s"])
@pytest.mark.parametrize("zone", ["Europe/Paris", "UTC+1", "Europe/Rome ", None, [], 4])
def test_unmapped_or_invalid_time_zone_is_rejected(identity, zone):
    profile, templates = load_bundle(identity)
    context = fixture_context()
    context["physical"]["time_zone"] = zone
    with pytest.raises(ValueError, match="time.?zone"):
        only_output(profile, templates, context)


